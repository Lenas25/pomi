// Bundles drizzle-kit's SQL migrations into a TypeScript module, so Metro needs no .sql loader
// (no babel.config.js / babel-plugin-inline-import). Run via `npm run db:generate`.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const drizzleDir = path.join(root, 'drizzle');
const journal = JSON.parse(fs.readFileSync(path.join(drizzleDir, 'meta', '_journal.json'), 'utf8'));

const migrations = {};
for (const entry of journal.entries) {
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  migrations[key] = fs.readFileSync(path.join(drizzleDir, `${entry.tag}.sql`), 'utf8');
}

const body = `// GENERATED by scripts/build-migrations.js from ./drizzle. Do not edit by hand.
export const migrations = ${JSON.stringify({ journal, migrations }, null, 2)};
`;

fs.writeFileSync(path.join(root, 'src', 'db', 'migrations.generated.ts'), body);
// drizzle-kit also emits drizzle/migrations.js, which imports .sql files; we don't use it.
fs.rmSync(path.join(drizzleDir, 'migrations.js'), { force: true });
console.log(`Bundled ${journal.entries.length} migration(s).`);
